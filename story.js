function reason(state) {
  const blocks = [
    { type: "p", text: "На кухне он кладёт шапку туда, где стояла кружка. Руки ледяные. Прячет их и сразу достаёт снова: некуда деть." }
  ];

  if (state.answer === "who") {
    blocks.push({
      type: "p",
      text: "Говорит быстро, пока ты не ушла в комнату."
    });
    blocks.push({
      type: "say",
      who: "Серёжа",
      text: "Я был уже внизу. У подъезда выходила девчонка, чужая, я её не знаю. Окликнула меня по имени. Я ей ответил, ты это слышала. Потом сразу поднялся."
    });
  } else if (state.answer === "hang") {
    blocks.push({
      type: "say",
      who: "Серёжа",
      text: "Я слышал, как ты молчишь. Всё время слышу. Даже когда связи нет."
    });
    blocks.push({
      type: "p",
      text: "Этого он знать не может. До тебя доходит не сразу."
    });
  } else {
    blocks.push({
      type: "say",
      who: "Серёжа",
      text: "Я сказал «один», потому что так короче. Это было вранье на одну минуту. Я думал, минута уместится."
    });
  }

  if (state.reply === "hold") {
    blocks.push({
      type: "say",
      who: "Серёжа",
      text: "И «не начинай» я сказал зря. Рядом стояла чужая."
    });
  }

  return {
    type: "prose",
    kicker: "Кухня",
    blocks,
    next: "hold",
    cta: "Дальше"
  };
}

